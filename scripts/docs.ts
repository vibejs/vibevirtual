import { readFile, writeFile } from 'node:fs/promises';
import { createHighlighter } from 'shiki';
import { Marked } from 'marked';
import { compile } from '@usevibejs/compiler';

const ids = [
  'getting-started',
  'architecture',
  'virtualizers',
  'layouts',
  'advanced',
  'accessibility',
  'ecosystem',
  'reference',
  'troubleshooting',
  'performance',
];
const highlighter = await createHighlighter({
  themes: ['github-light', 'github-dark'],
  langs: ['vue', 'typescript', 'shellscript', 'json'],
});
const markdown = new Marked({
  renderer: {
    code({ text, lang }) {
      const language = lang === 'vibe' ? 'vue' : lang === 'sh' ? 'shellscript' : lang || 'text';
      if (lang === 'vibe') {
        const result = compile(text, {
          filename: 'Documentation.vibe',
          id: 'docsample',
          dev: false,
        });
        if (result.diagnostics.length) throw new Error(JSON.stringify(result.diagnostics));
      }
      return `<div class="code-sample"><button type="button" data-copy-code aria-label="Copy code">Copy code</button>${highlighter.codeToHtml(text, { lang: language, themes: { light: 'github-light', dark: 'github-dark' } })}</div>`;
    },
  },
});
const pages = [];
for (const id of ids) {
  let source = await readFile(`docs/${id}.md`, 'utf8');
  for (const match of source.matchAll(/<!-- example:(\w+) -->/g)) {
    const example = await readFile(`examples/playground/src/${match[1]}.vibe`, 'utf8');
    source = source.replace(match[0], `\n\`\`\`vibe\n${example}\n\`\`\`\n`);
  }
  pages.push({
    id,
    title: source.match(/^# (.+)/)?.[1] ?? id,
    html: await markdown.parse(source),
    search: source.replace(/<[^>]*>/g, ''),
  });
}
await writeFile(
  'examples/playground/src/docs.generated.ts',
  `// Generated by scripts/docs.ts from verified .vibe examples.\nexport const pages = ${JSON.stringify(pages)};\n`,
);
highlighter.dispose();
process.stdout.write(
  `Generated ${pages.length} documentation pages with validated .vibe examples.\n`,
);
